    private int tam = 12; // Tamaño de fuente actual
    private final int MIN_FONT_SIZE = 12;
    private final int MAX_FONT_SIZE = 40;
    private void jtpCodeMouseWheelMoved(java.awt.event.MouseWheelEvent evt) {//GEN-FIRST:event_jtpCodeMouseWheelMoved
        // 1. Verificar si la tecla CTRL está presionada EN ESTE MOMENTO
        if (evt.isControlDown()) {

            // 2. Obtener la dirección de la rueda del ratón
            int rotation = evt.getWheelRotation();

            if (rotation < 0) {
                // Rueda hacia arriba -> Aumentar tamaño de fuente
                if (tam < MAX_FONT_SIZE) {
                    tam++;
                }
            } else {
                // Rueda hacia abajo -> Disminuir tamaño de fuente
                if (tam > MIN_FONT_SIZE) {
                    tam--;
                }
            }

            // 3. Aplicar la nueva fuente al JTextPane
            jtpCode.setFont(new Font("Segoe UI", Font.PLAIN, tam));
            coloreador.cambiarTamaño(tam);

            numerolinea = new NumeroLinea(jtpCode);

            ScrollCode.setRowHeaderView(numerolinea);

            evt.consume();
        } else {

            // CASO 2: CTRL NO está presionado -> Hacemos SCROLL
            // Como hemos interceptado el evento, debemos reenviarlo manualmente
            // al JScrollPane para que pueda procesarlo y realizar el scroll.
            if (ScrollCode != null && ScrollCode.getVerticalScrollBar().isVisible()) {

                // Obtenemos todos los listeners de la rueda del ratón que tiene el JScrollPane
                for (java.awt.event.MouseWheelListener listener : ScrollCode.getMouseWheelListeners()) {
                    // Y le decimos a cada uno que procese el evento
                    listener.mouseWheelMoved(evt);
                }
            }
        }
    }//GEN-LAST:event_jtpCodeMouseWheelMoved

