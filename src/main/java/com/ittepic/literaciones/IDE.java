    private void btnguardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnguardarActionPerformed
        JFileChooser fileChooser = new JFileChooser();

        FileNameExtensionFilter filter = new FileNameExtensionFilter(
                "Archivos LIT (*.lit)", "lit");
        fileChooser.setFileFilter(filter);
        fileChooser.setSelectedFile(new File("Literacion.lit"));

        int opcion = fileChooser.showSaveDialog(this);
        if (opcion == JFileChooser.APPROVE_OPTION) {
            File archivo = fileChooser.getSelectedFile();

            String filePath = archivo.getAbsolutePath();

            if (!filePath.toLowerCase().endsWith(".lit")) {
                archivo = new File(filePath + ".lit");
            }

            try (FileWriter fw = new FileWriter(archivo)) {
                fw.write(jtpCode.getText());
                JOptionPane.showMessageDialog(this, "Archivo guardado correctamente.");
            } catch (IOException ex) {
                JOptionPane.showMessageDialog(this, "Error al guardar: " + ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnguardarActionPerformed

    private void btnnuevoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnnuevoActionPerformed
// 1. Definición de la constante para la extensión
        final String EXTENSION = ".lit";

        // Comprueba si hay texto en el área antes de preguntar
        if (!jtpCode.getText().isEmpty()) {

            // Pregunta al usuario si desea guardar
            int opcion = JOptionPane.showConfirmDialog(
                    this,
                    "¿Deseas guardar el archivo actual antes de crear uno nuevo?",
                    "Confirmar",
                    JOptionPane.YES_NO_CANCEL_OPTION
            );

            // Si el usuario elige SÍ (Guardar)
            if (opcion == JOptionPane.YES_OPTION) {

                JFileChooser fileChooser = new JFileChooser();

                FileNameExtensionFilter filter = new FileNameExtensionFilter("Archivos LIT (*.lit)", "lit");
                fileChooser.setFileFilter(filter);
                fileChooser.setSelectedFile(new File("Literacion" + EXTENSION));

                int guardar = fileChooser.showSaveDialog(this);

                if (guardar == JFileChooser.APPROVE_OPTION) {

                    File archivo = fileChooser.getSelectedFile();
                    String filePath = archivo.getAbsolutePath();

                    if (!filePath.toLowerCase().endsWith(EXTENSION)) {
                        archivo = new File(filePath + EXTENSION);
                    }

                    try (FileWriter fw = new FileWriter(archivo)) {
                        fw.write(jtpCode.getText());
                        JOptionPane.showMessageDialog(this, "Archivo guardado correctamente.");
                        jtpCode.setText("");
                    } catch (IOException ex) {
                        JOptionPane.showMessageDialog(this, "Error al guardar: " + ex.getMessage());
                    }

                }
            } else if (opcion == JOptionPane.NO_OPTION) {
                jtpCode.setText("");
            } else if (opcion == JOptionPane.CANCEL_OPTION) {
            }

        } else {
            jtpCode.setText("");
        }
    }//GEN-LAST:event_btnnuevoActionPerformed

    private void btnCompilarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCompilarActionPerformed
        // Limpiar paneles de errores
        jtaOutput.setText("");
        jtpSeman.setText("");
        
        //REINICIO CODIGO INTERMEDIO ALMACENADO
        CodeGenerator.getInstance().reset();

        // ------------ ANALISIS LEXICO -----------------------------
        //Recuperamos el codigo escrito por el usuario
        String code = jtpCode.getText();

        //flujo de caracteres
        CharStream cs = CharStreams.fromString(code);

        //tokenizar el texto, le enviamos el textfield para que registre los errores
        lexer = new CustomLexer(cs, jtaOutput);

        //Buffer de tokens
        tokens = new CommonTokenStream(lexer);

        // ---------------- ANALISIS SINTACTICO -------------------------
        parser = new CustomParser(tokens, jtaOutput);

        // Se genera el arbol comenzando desde programa que es nuestro nodo inicial
        arbol = parser.programa();
        btnarbol.setEnabled(true);

        // REVISAR ERRORES LEXICOS
        List<String> LexLisErr = lexer.listaErrores;
        if (!LexLisErr.isEmpty()) {
            StringBuilder sb = new StringBuilder();
            sb.append("Se encontraron los siguientes errores lexicos:\n\n");
            for (String error : LexLisErr) {
                sb.append(error).append("\n");
            }
            jtaOutput.append(sb.toString());
        }

        //REVISAR ERRORES SEMANTICOS
        List<String> ErrorSem = parser.listaErrores;
        if (!ErrorSem.isEmpty()) {
            StringBuilder sb = new StringBuilder();
            sb.append("Se encontraron los siguientes errores semánticos:\n\n");
            for (String error : ErrorSem) {
                sb.append(error).append("\n");
            }
            jtpSeman.setText(sb.toString());
            jtaOutput.append("\n\nCompilación fallida debido a errores semánticos.");
        }

        boolean ErrorLex = lexer.listaErrores.isEmpty();

        boolean ErrorPar = parser.ErrorSintax();

        if (ErrorLex && ErrorPar && ErrorSem.isEmpty()) {
            jtaOutput.append("\n --- COMPILADO CORRECTAMENTE SIN ERRORES ---");
            jtpSeman.setText("No se encontraron errores semánticos");
        } else {
            jtaOutput.append("\n --- COMPILACION FALLIDA. -----------");
        }

        tabbedPane.setSelectedIndex(0);

        // --- FASE DE GENERACIÓN Y OPTIMIZACIÓN DE CÓDIGO 3DC ---
        // 1. Obtener la instancia del generador de código
        CodeGenerator cg = CodeGenerator.getInstance();

        // 2. Obtener el código 3DC original (tal como lo generó el parser)
        List<Instruction3DC> codigoOriginal = cg.getThreeAddressCode();

        // 🖥️ ⬇️ AQUÍ SE IMPRIME LA PRIMERA LISTA ⬇️
        System.out.println("--- CÓDIGO 3DC ORIGINAL (" + codigoOriginal.size() + " instrucciones) ---");
        StringBuilder textoIntermedio = new StringBuilder();
        textoIntermedio.append("--- CÓDIGO 3DC ORIGINAL (").append(codigoOriginal.size()).append(" instrucciones) ---\n");
        int line = 1;
        for (Instruction3DC instr : codigoOriginal) {
            System.out.println(instr);
            textoIntermedio.append(line++).append(".\t").append(instr).append("\n");
        }
        jtpIntermedio.setText(textoIntermedio.toString());
        System.out.println("---------------------------------------");

        // 3. ¡AQUÍ ES DONDE SE EJECUTA LA OPTIMIZACIÓN!
        try {
            optimizar miOptimizador = new optimizar();
            List<Instruction3DC> codigoOptimizado = miOptimizador.optimizar(codigoOriginal);

            // Imprimimos la lista optimizado
            System.out.println("--- CÓDIGO 3DC OPTIMIZADO (" + codigoOptimizado.size() + " instrucciones) ---");
            StringBuilder textoOptimizado = new StringBuilder();
            textoOptimizado.append("--- CÓDIGO 3DC OPTIMIZADO (").append(codigoOptimizado.size()).append(" instrucciones) ---\n");
            int linea = 1;
            for (Instruction3DC instr : codigoOptimizado) {
                System.out.println(instr);
                textoOptimizado.append(linea++).append(".\t").append(instr).append("\n");
            }
            jtpOptimizado.setText(textoOptimizado.toString());
            System.out.println("------------------------------------------");

        } catch (Exception e) {
            System.err.println("Error grave durante la fase de optimización: " + e.getMessage());
            e.printStackTrace();
        }


    }//GEN-LAST:event_btnCompilarActionPerformed

    private void mostrarTablaSimbolos() {

        Map<String, Simbolo> datos = parser.tablaSimbolos;

        if (this.tblSimbol == null) {
            return;
        }

// Nombres de las columnas
        String[] columnas = {"Nombre", "Valor", "Tipo"};

// Modelo de la tabla
        DefaultTableModel modelo = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                // Retornar false hace que ninguna celda sea editable
                return false;
            }
        };

// Recorremos el mapa y agregamos cada símbolo
        for (Map.Entry<String, Simbolo> entry : datos.entrySet()) {
            String nombre = entry.getKey();
            Object valor;
            String tipo;
            try {
                valor = entry.getValue().getValor();
                tipo = entry.getValue().getTipo();
            } catch (NullPointerException e) {
                valor = "NULO";
                tipo = "NULO";
            }

            modelo.addRow(new Object[]{nombre, valor, tipo});
        }

// Asignar el modelo a la JTable
        tblSimbol.setModel(modelo);
    }

